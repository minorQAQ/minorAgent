/**
 * 按当前小时返回一条随机标语（已替换时间占位符）。
 * @param {Date} [now]
 * @returns {string}
 */
export function getSlogan(now = new Date()) {
  const h = now.getHours();
  const groups = Object.values(SLOGANS);
  const group = groups.find((g) => h >= g.range[0] && h < g.range[1]) || SLOGANS.night;
  const items = group.items;
  const text = items[Math.floor(Math.random() * items.length)];
  return text
    .replace(/\{hh\}/g, String(h).padStart(2, "0"))
    .replace(/\{h\}/g, String(h));
}
